"""
Auto-generate ROADMAP.md from the actual state of the project.

Reads:
  - kofty/transpiler.py  (builtins, reserved words, supported nodes)
  - tests/*.py                  (test counts)
  - examples/*.is               (demo programs)
  - ROADMAP.manual.md           (human-written plans and notes)

Writes:
  - ROADMAP.md                  (auto-generated facts + manual section)

Usage:
    python generate_roadmap.py
"""

import ast
import datetime
from pathlib import Path


ROOT = Path(__file__).parent


def count_tests(path: Path) -> int:
    """Count function definitions starting with `test_`."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return sum(
        1 for node in ast.walk(tree)
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_")
    )


def extract_builtins() -> list:
    """Read the BUILTINS dict from transpiler.py."""
    tree = ast.parse((ROOT / "interscript" / "transpiler.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "BUILTINS":
                    if isinstance(node.value, ast.Dict):
                        return [
                            k.value for k in node.value.keys
                            if isinstance(k, ast.Constant)
                        ]
    return []


def extract_reserved_count() -> int:
    """Count entries in CPP_RESERVED."""
    tree = ast.parse((ROOT / "interscript" / "transpiler.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "CPP_RESERVED":
                    if isinstance(node.value, ast.Set):
                        return len(node.value.elts)
    return 0


def extract_visit_methods() -> list:
    """List all visit_* methods in CppEmitter."""
    tree = ast.parse((ROOT / "interscript" / "transpiler.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == "CppEmitter":
            return sorted(
                n.name for n in node.body
                if isinstance(n, ast.FunctionDef) and n.name.startswith("visit_")
            )
    return []


def list_examples() -> list:
    """List .is files in examples/."""
    ex_dir = ROOT / "examples"
    if not ex_dir.exists():
        return []
    return sorted(p.name for p in ex_dir.glob("*.is"))


def main():
    # Count tests
    test_files = sorted((ROOT / "tests").glob("test_*.py"))
    test_counts = {p.name: count_tests(p) for p in test_files}
    total_tests = sum(test_counts.values())

    # Extract facts from transpiler
    builtins = extract_builtins()
    reserved_count = extract_reserved_count()
    visit_methods = extract_visit_methods()
    examples = list_examples()

    # Timestamp
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")

    # Auto-generated section
    auto = []
    auto.append("# InterScript — Project Roadmap")
    auto.append("")
    auto.append(f"_Auto-generated on {now}. Do not edit this file by hand;_")
    auto.append(f"_edit `ROADMAP.manual.md` instead, then run `python generate_roadmap.py`._")
    auto.append("")
    auto.append("---")
    auto.append("")
    auto.append("## Current state (auto)")
    auto.append("")
    auto.append(f"- **Tests passing:** {total_tests}")
    auto.append(f"  - " + ", ".join(f"{name}: {count}" for name, count in test_counts.items()))
    auto.append(f"- **Built-in functions:** {len(builtins)}")
    auto.append(f"  - `{'`, `'.join(builtins)}`")
    auto.append(f"- **C++ reserved words blocked:** {reserved_count}")
    auto.append(f"- **Supported AST node types:** {len(visit_methods)}")
    auto.append(f"  - `{'`, `'.join(visit_methods)}`")
    auto.append(f"- **Example programs:** {len(examples)}")
    for name in examples:
        auto.append(f"  - `examples/{name}`")
    auto.append("")
    auto.append("---")
    auto.append("")

    # Read manual section
    manual_path = ROOT / "ROADMAP.manual.md"
    if manual_path.exists():
        manual = manual_path.read_text(encoding="utf-8")
    else:
        manual = "_(ROADMAP.manual.md not found)_"

    # Combine
    content = "\n".join(auto) + manual + "\n"

    (ROOT / "ROADMAP.md").write_text(content, encoding="utf-8")
    print(f"✅ Wrote ROADMAP.md ({len(content)} bytes)")
    print(f"   - {total_tests} tests across {len(test_files)} files")
    print(f"   - {len(builtins)} builtins")
    print(f"   - {len(visit_methods)} supported AST node types")
    print(f"   - {len(examples)} example programs")


if __name__ == "__main__":
    main()
